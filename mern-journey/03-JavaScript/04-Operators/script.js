let price = 500;
let quantity = 3;

// Total price
console.log("Total Price:", price + quantity);

// Difference
console.log("Difference:", price - quantity);

// Multiplication
console.log("Multiplication:", price * quantity);

// Division
console.log("Division:", price / quantity);

// Remainder
console.log("Remainder:", price % quantity);

// Comparisons
console.log(price > 300);
console.log(quantity === 3);
console.log(price < 300);
console.log(quantity !== 3);

// Logical AND &&
console.log(price > 300 && quantity ===3);

// Logical OR ||
console.log(price > 300 || quantity ===3);

// Logical NOT !
console.log(!(price > 300));

